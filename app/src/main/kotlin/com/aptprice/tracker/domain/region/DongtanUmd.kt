package com.aptprice.tracker.domain.region

/**
 * 화성시(LAWD_CD 41590) 는 실거래가 API 에서 시 단위 코드 하나로만 조회된다.
 * 따라서 동탄 지역만 보려면 응답의 법정동명(umdNm) 으로 클라이언트에서 걸러내야 한다.
 *
 * 아래 목록은 화성시 동탄1~9동(동탄출장소) 관할 법정동이다.
 * 출처: 화성시 행정구역 현황(화성시청 고시) 및 행정안전부 법정동코드 전체자료.
 */
object DongtanUmd {

    /**
     * 작업지시서에 명시된 기본 대상 법정동 11곳.
     * 동탄1신도시(반송동·석우동·능동) 와 동탄2신도시 주요 법정동을 포함한다.
     */
    val DEFAULT: Set<String> = setOf(
        // 동탄1신도시
        "반송동",
        "석우동",
        "능동",
        // 동탄2신도시
        "청계동",
        "영천동",
        "신동",
        "목동",
        "산척동",
        "송동",
        "장지동",
        "오산동",
    )

    /**
     * 동탄2신도시 확장 구역까지 포함한 목록.
     *
     * DEFAULT 에 방교동·중동·금곡동을 추가한다. 세 곳 모두 동탄 행정동 관할 법정동이지만
     * 작업지시서의 기본 목록에는 빠져 있어, 사용 여부를 앱 설정에서 고를 수 있도록 분리해 둔다.
     * 임의로 만들어 낸 값이 아니라 실제 화성시 동탄 관할 법정동이다.
     */
    val EXTENDED: Set<String> = DEFAULT + setOf(
        "방교동",
        "중동",
        "금곡동",
    )
}
